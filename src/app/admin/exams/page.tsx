'use client';

import React, { useEffect, useState } from 'react';
import Link from 'next/link';
import AdminLayout from '@/components/admin/AdminLayout';
import { fetchAllPlatformExams } from '@/lib/firebase/admin';
import { Exam } from '@/types';
import { BookOpen, Search, ExternalLink, RefreshCw } from 'lucide-react';

export default function AdminExamsPage() {
  const [exams, setExams] = useState<Exam[]>([]);
  const [loading, setLoading] = useState(true);
  const [searchTerm, setSearchTerm] = useState('');

  const loadExams = async () => {
    setLoading(true);
    try {
      const allExams = await fetchAllPlatformExams();
      setExams(allExams);
    } catch (err) {
      console.error('Failed to load platform exams:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadExams();
  }, []);

  const filteredExams = exams.filter(
    (e) =>
      e.title.toLowerCase().includes(searchTerm.toLowerCase()) ||
      e.shareCode.toLowerCase().includes(searchTerm.toLowerCase()) ||
      e.subject.toLowerCase().includes(searchTerm.toLowerCase())
  );

  return (
    <AdminLayout>
      <div className="space-y-6">
        {/* Header */}
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 border-b border-slate-800 pb-5">
          <div>
            <h1 className="text-2xl sm:text-3xl font-black tracking-tight text-white flex items-center gap-2.5">
              <BookOpen className="w-7 h-7 text-indigo-500" />
              Platform Exam Directory
            </h1>
            <p className="text-xs text-slate-400 mt-1">
              View all interactive CDF fill-in-the-blank exams generated by teachers across the system.
            </p>
          </div>

          <button
            onClick={loadExams}
            className="px-3.5 py-2 bg-slate-800 hover:bg-slate-700 text-slate-200 font-bold text-xs rounded-xl transition-all flex items-center gap-2"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
            Refresh List
          </button>
        </div>

        {/* Search */}
        <div className="relative max-w-md">
          <Search className="w-4 h-4 text-slate-500 absolute left-3.5 top-3" />
          <input
            type="text"
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            placeholder="Search by title, subject, or share code..."
            className="w-full pl-10 pr-4 py-2 bg-slate-900 border border-slate-800 rounded-xl text-xs text-white placeholder-slate-500 outline-none focus:border-indigo-500"
          />
        </div>

        {/* Exams Table */}
        <div className="bg-slate-900 border border-slate-800 rounded-2xl overflow-hidden shadow-xl">
          <div className="overflow-x-auto">
            <table className="w-full text-left border-collapse">
              <thead>
                <tr className="bg-slate-950/80 text-[11px] font-extrabold uppercase tracking-wider text-slate-400 border-b border-slate-800">
                  <th className="py-4 px-6">Exam Title</th>
                  <th className="py-4 px-6">Teacher</th>
                  <th className="py-4 px-6">Class / Subject</th>
                  <th className="py-4 px-6">Share Code</th>
                  <th className="py-4 px-6 text-right">Attempts</th>
                  <th className="py-4 px-6 text-right">Link</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-800/80 text-xs">
                {filteredExams.length === 0 ? (
                  <tr>
                    <td colSpan={6} className="py-8 text-center text-slate-500">
                      No exams found matching your search.
                    </td>
                  </tr>
                ) : (
                  filteredExams.map((e) => (
                    <tr key={e.id} className="hover:bg-slate-800/40 transition-colors">
                      <td className="py-4 px-6 font-bold text-white">{e.title}</td>
                      <td className="py-4 px-6 text-slate-300 font-medium">{e.teacherName || 'Teacher'}</td>
                      <td className="py-4 px-6 text-slate-400">
                        {e.className} • {e.subject}
                      </td>
                      <td className="py-4 px-6 font-mono text-indigo-400 font-bold">{e.shareCode}</td>
                      <td className="py-4 px-6 text-right font-black text-white">{e.attemptCount || 0}</td>
                      <td className="py-4 px-6 text-right">
                        <Link
                          href={`/exam/${e.shareCode}`}
                          target="_blank"
                          className="p-2 text-indigo-400 hover:text-indigo-300 inline-flex items-center gap-1 font-bold text-xs"
                        >
                          Open <ExternalLink className="w-3.5 h-3.5" />
                        </Link>
                      </td>
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        </div>
      </div>
    </AdminLayout>
  );
}
